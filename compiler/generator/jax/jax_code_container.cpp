/*
JAX backend and module description:
- The JAX backend generates several functions:
  1. `setup(self) -> None:`
  2. `_initialize_carry(self, x: jnp.ndarray, length: int):`
  3. `tick(self, params: dict, state: dict, inputs: jnp.array) -> Tuple[dict, jnp.ndarray]:`

`setup` implements a method of a flax.linen.Module. In this method, we are allowed to assign attributes
to `self`. For example, a commonly autogenerated property is a constant related to the sample-rate:
```python
self._fConst0 = np.minimum(np.float32(1.92e+05), np.maximum(np.float32(1.0), (self._fSampleRate)))
```

Other attributes are set indirectly because `setup` may call `self.add_hslider(...)`, which is implemented by
an architecture file, which almost certainly calls `self.param(...)`

`setup` is also where signals for rdtables are created. They are constants, so they shouldn't be in the "state"
which is repeatedly modified by the `tick` function.

`_initialize_carry` is where the "state"/"carry" is initialized. It cannot set anything to `self`.
This is where delay lines and signals for rwtables are created.
We also have a bias towards using numpy operations here instead of JAX numpy operations because they're faster.
The code should cast to JAX numpy late inside `_initialize_carry`.

`tick` returns a tuple of the new state and the new audio, which could have multiple channels.
It's the closest thing to a "compute" method compared to other Faust backends. Since it computes one new sample,
not a block of samples, it's similar to `-os` or `--one-sample` from command-line Faust in other backends.
  
The architecture file (`architecture/jax/minimal.py`) ties all of these functions together.

One tricky part of JAX is modifying arrays in-place:
https://jax.readthedocs.io/en/latest/_autosummary/jax.numpy.ndarray.at.html

Whereas C++ would look like:
`fRec1[0] = fTemp0`
in JAX we have to do:
`state["fRec1"] = state["fRec1"].at[0].set(fTemp0)`

Also, this at-and-set operation is slow, so we try to only use it inside the tick method as necessary.
This is why in all other places (like initializing waveforms and soundfiles) we use non-JAX numpy.

The JAXInitFieldsVisitor class does initialization for waveforms. We also use fUseNumpy in this
decision making. The `JAXCodeContainer` later converts the numpy arrays to jax numpy at the beginning of the `tick` method.
*/

